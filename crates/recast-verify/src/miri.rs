//! V4 Miri integration.
//!
//! Miri interprets Rust's mid-level IR and reports undefined behavior that a
//! checked compile and run do not catch: out-of-bounds access, invalid
//! references, uninitialized reads and aliasing violations. It needs a test
//! target to run, so the generated library is copied into a small crate with
//! one `#[test]` per case call, built from the same arguments V2 executed.
//!
//! The generated crate itself is not modified: keeping V1 and the mutation
//! harness pointed at the translation alone. Miri runs only when the host
//! toolchain provides `cargo miri`; an unavailable run is a note, not a pass.
//!
//! The test target checks for undefined behavior, not values. The V2
//! differential already compared every call's output with the C original; a
//! Miri test that also asserted values would duplicate that comparison with a
//! second source of expected values.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::time::Duration;

use recast_ir::Program;

use crate::driver;
use crate::hygiene::Check;
use crate::sandbox::Sandbox;
use crate::{write, Case, Error, Options};

/// The Miri crate written for one case.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Target {
    pub crate_dir: PathBuf,
    /// The number of call tests in the target.
    pub calls: usize,
}

/// Write the Miri crate for `case`: a copy of the generated library and a test
/// target with one test per call. `None` means the case defined no calls, so
/// there is nothing to interpret.
pub fn prepare(
    options: &Options,
    crate_dir: &Path,
    program: &Program,
    case: &Case,
) -> Result<Option<Target>, Error> {
    if case.calls.is_empty() {
        return Ok(None);
    }
    let root = options.work.join("v4/miri/crate");
    let src = root.join("src");
    let tests = root.join("tests");
    for directory in [&src, &tests] {
        std::fs::create_dir_all(directory).map_err(|error| Error::Io {
            path: directory.clone(),
            message: error.to_string(),
        })?;
    }

    let library =
        std::fs::read_to_string(crate_dir.join("src/lib.rs")).map_err(|error| Error::Io {
            path: crate_dir.join("src/lib.rs"),
            message: error.to_string(),
        })?;
    write(&src.join("lib.rs"), &library)?;
    write(
        &root.join("Cargo.toml"),
        "\
[package]
name = \"recast-miri-check\"
version = \"0.1.0\"
edition = \"2021\"

[lib]
path = \"src/lib.rs\"

[workspace]
",
    )?;

    let mut source = String::from(
        "\
// Generated by recast: one test per V2 call, interpreted by Miri.
#![allow(unused_mut, unused_variables)]

#[path = \"../src/lib.rs\"]
mod generated;
",
    );
    for (index, call) in case.calls.iter().enumerate() {
        let lines = driver::rust_test_call(program, call)?;
        // A failure to format a String cannot happen; the call is above all
        // a compile-time check of the generated test source.
        let _ = writeln!(source, "\n#[test]\nfn call_{index}() {{");
        for line in &lines {
            // Every line is a statement; `rust_test_call` leaves the call
            // unterminated so the semicolon is added once here.
            let _ = writeln!(source, "    {line};");
        }
        source.push_str("}\n");
    }
    write(&tests.join("v4_miri.rs"), &source)?;

    Ok(Some(Target {
        crate_dir: root,
        calls: case.calls.len(),
    }))
}

/// `cargo miri` is installed and usable on this host.
pub fn available(options: &Options) -> bool {
    Command::new(&options.cargo)
        .args(["miri", "--version"])
        .output()
        .map(|output| {
            output.status.success() && String::from_utf8_lossy(&output.stdout).contains("miri")
        })
        .unwrap_or(false)
}

/// Run the target under Miri and record what happened. A failing test, an
/// undefined-behavior report or a timeout is a failed check.
pub fn run(options: &Options, target: &Target) -> Result<Check, Error> {
    let mut sandbox = Sandbox::new(options.work.join("v4/miri/scratch"));
    // Building the test target and interpreting std allocation code is slower
    // than a compiled driver run, so this check gets its own budget.
    sandbox.timeout = Duration::from_secs(300);
    sandbox.cpu_seconds = 300;
    let manifest = target.crate_dir.join("Cargo.toml");
    let args = vec![
        "miri".to_string(),
        "test".to_string(),
        "--offline".to_string(),
        "--quiet".to_string(),
        "--manifest-path".to_string(),
        manifest.display().to_string(),
    ];
    let output = sandbox.run_with_env(
        &resolve_program(&options.cargo),
        &args,
        &toolchain_environment(),
    )?;
    if output.success() {
        Ok(Check {
            passed: true,
            detail: format!(
                "Miri interpreted {} call test(s) on the translated crate and reported no undefined behavior",
                target.calls
            ),
        })
    } else {
        Ok(Check {
            passed: false,
            detail: format!(
                "cargo miri test failed{}: {}",
                if output.timed_out { " (timeout)" } else { "" },
                last_lines(
                    &format!("{}\n{}", output.stdout.trim_end(), output.stderr.trim_end()),
                    20
                )
            ),
        })
    }
}

/// The sandbox clears the environment, but Cargo needs the toolchain variables
/// it was launched with. None of these are secrets; they point at the toolchain.
fn toolchain_environment() -> Vec<(String, String)> {
    ["HOME", "RUSTUP_HOME", "CARGO_HOME", "PATH", "MIRI_SYSROOT"]
        .iter()
        .filter_map(|key| {
            std::env::var(key)
                .ok()
                .map(|value| ((*key).to_string(), value))
        })
        .collect()
}

/// The sandbox starts elsewhere, and its environment has no `PATH`, so a bare
/// `cargo` has to be resolved to the absolute path its launcher used.
fn resolve_program(program: &Path) -> PathBuf {
    if program.is_absolute() || program.components().count() > 1 {
        return program.to_path_buf();
    }
    if let Some(path) = std::env::var_os("PATH") {
        for directory in std::env::split_paths(&path) {
            let candidate = directory.join(program);
            if candidate.is_file() {
                return candidate;
            }
        }
    }
    program.to_path_buf()
}

fn last_lines(text: &str, count: usize) -> String {
    let lines: Vec<&str> = text
        .lines()
        .filter(|line| !line.trim().is_empty())
        .collect();
    lines[lines.len().saturating_sub(count)..].join("\n")
}

#[cfg(test)]
mod tests {
    use super::*;
    use recast_ir::{
        FnSig, Function, ItemId, Linkage, Param, Provenance, Target as IrTarget, Type,
    };

    fn add_program() -> Program {
        let mut program = Program::new(IrTarget::lp64("x86_64-unknown-linux-gnu"));
        let int = program.types.intern(Type::Int {
            bits: 32,
            signed: true,
            spelling: "int".to_string(),
        });
        program.add_function(Function {
            id: ItemId::function("add"),
            name: "add".to_string(),
            linkage: Linkage::External,
            signature: FnSig {
                params: vec![
                    Param {
                        name: Some("a".to_string()),
                        ty: int,
                    },
                    Param {
                        name: Some("b".to_string()),
                        ty: int,
                    },
                ],
                ret: int,
                variadic: false,
            },
            body: None,
            provenance: Provenance::synthesized(),
        });
        program
    }

    fn temp_dir(label: &str) -> PathBuf {
        let directory =
            std::env::temp_dir().join(format!("recast-miri-{label}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&directory);
        std::fs::create_dir_all(&directory).expect("test directory");
        directory
    }

    #[test]
    fn prepare_writes_one_test_per_call() {
        let root = temp_dir("prepare");
        let crate_dir = root.join("rust");
        std::fs::create_dir_all(crate_dir.join("src")).expect("library directory");
        std::fs::write(
            crate_dir.join("src/lib.rs"),
            "pub fn add(a: i32, b: i32) -> i32 {\n    a + b\n}\n",
        )
        .expect("library");
        let case = Case {
            schema: "recast-case/1".to_string(),
            calls: vec![
                crate::Call {
                    function: "add".to_string(),
                    args: vec![serde_json::json!(1), serde_json::json!(2)],
                },
                crate::Call {
                    function: "add".to_string(),
                    args: vec![serde_json::json!(3), serde_json::json!(4)],
                },
            ],
            sweeps: Vec::new(),
            test_command: None,
        };
        let options = Options::new(&root);

        let target = prepare(&options, &crate_dir, &add_program(), &case)
            .expect("prepare")
            .expect("a case with calls has a target");
        assert_eq!(target.calls, 2);
        let tests = std::fs::read_to_string(target.crate_dir.join("tests/v4_miri.rs"))
            .expect("test target");
        assert_eq!(tests.matches("#[test]").count(), 2, "{tests}");
        assert!(tests.contains("generated::add(1, 2)"), "{tests}");
        assert!(tests.contains("generated::add(3, 4)"), "{tests}");
        assert!(std::fs::read_to_string(target.crate_dir.join("Cargo.toml"))
            .expect("manifest")
            .contains("name = \"recast-miri-check\""));

        let _ = std::fs::remove_dir_all(&root);
    }

    #[test]
    fn a_case_without_calls_has_no_target() {
        let root = temp_dir("empty");
        let crate_dir = root.join("rust");
        std::fs::create_dir_all(crate_dir.join("src")).expect("library directory");
        std::fs::write(crate_dir.join("src/lib.rs"), "pub fn f() {}\n").expect("library");
        let case = Case {
            schema: "recast-case/1".to_string(),
            calls: Vec::new(),
            sweeps: Vec::new(),
            test_command: None,
        };
        let options = Options::new(&root);
        assert!(prepare(&options, &crate_dir, &add_program(), &case)
            .expect("prepare")
            .is_none());

        let _ = std::fs::remove_dir_all(&root);
    }

    #[cfg(unix)]
    fn fake_cargo(root: &Path, test_exit: u8) -> (PathBuf, Options, PathBuf) {
        use std::os::unix::fs::PermissionsExt;

        let crate_dir = root.join("rust");
        std::fs::create_dir_all(crate_dir.join("src")).expect("library directory");
        std::fs::write(
            crate_dir.join("src/lib.rs"),
            "pub fn add(a: i32, b: i32) -> i32 {\n    a + b\n}\n",
        )
        .expect("library");
        let cargo = root.join("cargo");
        std::fs::write(
            &cargo,
            format!(
                "#!/bin/sh\nif [ \"$1\" = \"miri\" ] && [ \"$2\" = \"--version\" ]; then\n  echo 'miri 0.1.0'\n  exit 0\nfi\nif [ \"$1\" = \"miri\" ] && [ \"$2\" = \"test\" ]; then\n  echo 'running 1 test'\n  exit {test_exit}\nfi\nexit 3\n"
            ),
        )
        .expect("fake cargo");
        std::fs::set_permissions(&cargo, std::fs::Permissions::from_mode(0o755))
            .expect("executable");
        let mut options = Options::new(root);
        options.cargo = cargo.clone();
        (crate_dir, options, cargo)
    }

    #[cfg(unix)]
    fn one_call() -> Case {
        Case {
            schema: "recast-case/1".to_string(),
            calls: vec![crate::Call {
                function: "add".to_string(),
                args: vec![serde_json::json!(1), serde_json::json!(2)],
            }],
            sweeps: Vec::new(),
            test_command: None,
        }
    }

    #[cfg(unix)]
    #[test]
    fn a_successful_miri_run_is_a_passed_check() {
        let root = temp_dir("fake-cargo");
        let (crate_dir, options, _) = fake_cargo(&root, 0);
        assert!(available(&options));
        let target = prepare(&options, &crate_dir, &add_program(), &one_call())
            .expect("prepare")
            .expect("target");
        let check = run(&options, &target).expect("miri run");
        assert!(check.passed, "{check:?}");
        assert!(check.detail.contains("1 call test"));

        let _ = std::fs::remove_dir_all(&root);
    }

    #[cfg(unix)]
    #[test]
    fn a_failing_miri_run_fails_the_check() {
        let root = temp_dir("fake-cargo-fail");
        let (crate_dir, options, _) = fake_cargo(&root, 1);
        let target = prepare(&options, &crate_dir, &add_program(), &one_call())
            .expect("prepare")
            .expect("target");
        let check = run(&options, &target).expect("miri run");
        assert!(!check.passed, "{check:?}");
        assert!(check.detail.contains("cargo miri test failed"), "{check:?}");

        let _ = std::fs::remove_dir_all(&root);
    }
}
