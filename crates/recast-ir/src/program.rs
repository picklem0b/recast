//! The structured TIR program.
//!
//! This is a deliberately small M0 slice of document 04: functions, scalar and
//! pointer types, structured statements and expressions. Later milestones add
//! records, enums, macros and analysis fact tables without changing these IDs.

use crate::id::{ItemId, NodeId, TypeId};
use crate::types::TypeTable;
use crate::validate::ValidationError;

/// The TIR schema version carried by a program.
pub const SCHEMA_VERSION: u32 = 1;

/// The TIR schema name used in reports.
pub const SCHEMA_NAME: &str = "tir/1";

/// A source location in the original file.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Span {
    pub file: String,
    pub line: u32,
    pub column: u32,
}

impl Span {
    /// A location in a real source file.
    pub fn new(file: impl Into<String>, line: u32, column: u32) -> Self {
        Self {
            file: file.into(),
            line,
            column,
        }
    }

    /// The location used for a generated node.
    pub fn synthesized() -> Self {
        Self {
            file: "<synthesized>".to_string(),
            line: 0,
            column: 0,
        }
    }
}

/// Where a node came from.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Provenance {
    pub span: Span,
    pub synthesized: bool,
}

impl Provenance {
    /// A node copied from source.
    pub fn source(span: Span) -> Self {
        Self {
            span,
            synthesized: false,
        }
    }

    /// A node generated by recast.
    pub fn synthesized() -> Self {
        Self {
            span: Span::synthesized(),
            synthesized: true,
        }
    }
}

/// Byte order of the target.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Endian {
    Little,
    Big,
}

/// Target facts that decide integer widths and pointer layout.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Target {
    pub triple: String,
    pub pointer_bits: u8,
    pub int_bits: u8,
    pub long_bits: u8,
    pub long_long_bits: u8,
    pub char_is_signed: bool,
    pub endian: Endian,
    pub max_align: u32,
    pub size_t_bits: u8,
}

impl Target {
    /// The default LP64 target used by the M0 tests.
    pub fn lp64(triple: impl Into<String>) -> Self {
        Self {
            triple: triple.into(),
            pointer_bits: 64,
            int_bits: 32,
            long_bits: 64,
            long_long_bits: 64,
            char_is_signed: false,
            endian: Endian::Little,
            max_align: 16,
            size_t_bits: 64,
        }
    }
}

/// A source file known to the program.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct FileInfo {
    pub path: String,
}

/// Symbol visibility.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Linkage {
    External,
    Internal,
    None,
}

/// The C value category of an expression.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ValueCategory {
    LValue,
    PRValue,
    XValue,
}

/// A function parameter.
#[derive(Debug, Clone, PartialEq)]
pub struct Param {
    pub name: Option<String>,
    pub ty: TypeId,
}

/// A function signature.
#[derive(Debug, Clone, PartialEq)]
pub struct FnSig {
    pub params: Vec<Param>,
    pub ret: TypeId,
    pub variadic: bool,
}

/// A function item.
#[derive(Debug, Clone, PartialEq)]
pub struct Function {
    pub id: ItemId,
    pub name: String,
    pub linkage: Linkage,
    pub signature: FnSig,
    pub body: Option<Block>,
    pub provenance: Provenance,
}

/// One field of a record.
#[derive(Debug, Clone, PartialEq)]
pub struct FieldDef {
    pub name: String,
    pub ty: TypeId,
}

/// A struct or union definition.
#[derive(Debug, Clone, PartialEq)]
pub struct RecordDef {
    pub id: ItemId,
    pub name: String,
    pub fields: Vec<FieldDef>,
    /// `sizeof` under the target, in bytes; zero when the exporter did not
    /// report a layout.
    pub size: u64,
    pub align: u64,
    pub provenance: Provenance,
}

impl RecordDef {
    /// The index of a field by name.
    pub fn field(&self, name: &str) -> Option<usize> {
        self.fields.iter().position(|field| field.name == name)
    }
}

/// One enumerator and its value.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Enumerator {
    pub name: String,
    pub value: i64,
}

/// An enum definition.
#[derive(Debug, Clone, PartialEq)]
pub struct EnumDef {
    pub id: ItemId,
    pub name: String,
    pub underlying: TypeId,
    pub variants: Vec<Enumerator>,
    pub provenance: Provenance,
}

impl EnumDef {
    /// The value of an enumerator by name.
    pub fn variant(&self, name: &str) -> Option<&Enumerator> {
        self.variants.iter().find(|variant| variant.name == name)
    }
}

/// A file-scope constant or variable.
#[derive(Debug, Clone, PartialEq)]
pub struct Global {
    pub id: ItemId,
    pub name: String,
    pub ty: TypeId,
    pub init: Option<Expr>,
    pub is_const: bool,
    pub linkage: Linkage,
    pub provenance: Provenance,
}

/// One arm of a `switch`.
#[derive(Debug, Clone, PartialEq)]
pub struct Case {
    /// `None` is the `default` arm.
    pub label: Option<i64>,
    pub body: Block,
    pub falls_through: bool,
}

/// A lexical block.
#[derive(Debug, Clone, PartialEq, Default)]
pub struct Block {
    pub stmts: Vec<Stmt>,
}

/// A statement with its source identity.
#[derive(Debug, Clone, PartialEq)]
pub struct Stmt {
    pub id: NodeId,
    pub kind: StmtKind,
    pub provenance: Provenance,
}

/// The statement form.
#[derive(Debug, Clone, PartialEq)]
pub enum StmtKind {
    Decl {
        name: String,
        ty: TypeId,
        init: Option<Expr>,
    },
    Expr(Expr),
    If {
        cond: Expr,
        then_branch: Block,
        else_branch: Option<Block>,
    },
    While {
        cond: Expr,
        body: Block,
    },
    For {
        init: Option<Box<Stmt>>,
        cond: Option<Expr>,
        step: Option<Expr>,
        body: Block,
    },
    DoWhile {
        body: Block,
        cond: Expr,
    },
    Switch {
        scrutinee: Expr,
        cases: Vec<Case>,
    },
    Return(Option<Expr>),
    Break,
    Continue,
    Empty,
}

/// A typed expression with its source identity.
#[derive(Debug, Clone, PartialEq)]
pub struct Expr {
    pub id: NodeId,
    pub ty: TypeId,
    pub category: ValueCategory,
    pub kind: ExprKind,
    pub provenance: Provenance,
}

/// The expression form.
#[derive(Debug, Clone, PartialEq)]
pub enum ExprKind {
    IntLit(i64),
    FloatLit(f64),
    StringLit(String),
    CharLit(u32),
    BoolLit(bool),
    Null,
    Local(String),
    /// A reference to a file-scope constant or variable.
    Global(ItemId),
    /// A reference to an enumerator, carrying the value Clang assigned.
    EnumConst {
        item: ItemId,
        value: i64,
    },
    Member {
        base: Box<Expr>,
        field: String,
        arrow: bool,
    },
    Cond {
        cond: Box<Expr>,
        then_branch: Box<Expr>,
        else_branch: Box<Expr>,
    },
    InitList(Vec<Expr>),
    Unary {
        op: String,
        operand: Box<Expr>,
        postfix: bool,
    },
    Binary {
        op: String,
        lhs: Box<Expr>,
        rhs: Box<Expr>,
    },
    Assign {
        op: String,
        lhs: Box<Expr>,
        rhs: Box<Expr>,
    },
    Index {
        base: Box<Expr>,
        index: Box<Expr>,
    },
    Call {
        callee: Callee,
        args: Vec<Expr>,
    },
    Cast {
        to: TypeId,
        expr: Box<Expr>,
        implicit: bool,
    },
    Paren(Box<Expr>),
    Unsupported(String),
}

/// The callee of a call expression.
#[derive(Debug, Clone, PartialEq)]
pub enum Callee {
    Direct(ItemId),
    Indirect(Box<Expr>),
    Unresolved(String),
}

/// One lowered program.
#[derive(Debug, Clone, PartialEq)]
pub struct Program {
    pub schema_version: u32,
    pub target: Target,
    pub files: Vec<FileInfo>,
    pub functions: Vec<Function>,
    pub records: Vec<RecordDef>,
    pub enums: Vec<EnumDef>,
    pub globals: Vec<Global>,
    pub types: TypeTable,
}

impl Program {
    /// Create an empty program for `target`.
    pub fn new(target: Target) -> Self {
        Self {
            schema_version: SCHEMA_VERSION,
            target,
            files: Vec::new(),
            functions: Vec::new(),
            records: Vec::new(),
            enums: Vec::new(),
            globals: Vec::new(),
            types: TypeTable::new(),
        }
    }

    /// Record a source file. Duplicate paths are rejected by validation.
    pub fn add_file(&mut self, path: impl Into<String>) {
        self.files.push(FileInfo { path: path.into() });
    }

    /// Add a function item.
    pub fn add_function(&mut self, function: Function) {
        self.functions.push(function);
    }

    /// Look up a function by its item identifier.
    pub fn function(&self, id: &ItemId) -> Option<&Function> {
        self.functions.iter().find(|function| &function.id == id)
    }

    /// Look up a function by name.
    pub fn function_named(&self, name: &str) -> Option<&Function> {
        self.functions.iter().find(|function| function.name == name)
    }

    /// Look up a record by name.
    pub fn record(&self, name: &str) -> Option<&RecordDef> {
        self.records.iter().find(|record| record.name == name)
    }

    /// Look up an enum by name.
    pub fn enum_named(&self, name: &str) -> Option<&EnumDef> {
        self.enums.iter().find(|item| item.name == name)
    }

    /// Look up a global by name.
    pub fn global_named(&self, name: &str) -> Option<&Global> {
        self.globals.iter().find(|global| global.name == name)
    }

    /// Look up a global by its item identifier.
    pub fn global(&self, id: &ItemId) -> Option<&Global> {
        self.globals.iter().find(|global| &global.id == id)
    }

    /// Run every M0 validation invariant.
    pub fn validate(&self) -> Result<(), Vec<ValidationError>> {
        crate::validate::validate(self)
    }

    /// Render the deterministic textual dump.
    pub fn dump(&self) -> String {
        crate::dump::dump(self)
    }
}
